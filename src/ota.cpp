/**
 * @file ota.cpp
 * @brief HTTP OTA firmware update implementation.
 *
 * Routes:
 *   GET  /ota  — serves a minimal HTML upload form
 *   POST /ota  — receives multipart firmware binary and flashes it
 *
 * The upload runs inside ESPAsyncWebServer's lwIP TCPIP task (Core 0);
 * the Arduino loop on Core 1 is never blocked.
 *
 * The Arduino Update library wraps the ESP-IDF esp_ota API, handling
 * partition selection, sequential writes, image validation, and the
 * boot-partition switch atomically before the reboot.
 */

