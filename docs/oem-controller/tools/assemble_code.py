"""
@file assemble_code.py
@brief Split the corrected appendix pages (US6446444 PDF pp13-104) into module files.

Input: a directory of per-page transcriptions p-NNN.txt (page furniture already
removed). Modules start at the printed "<NAME> MODULE" heading lines.
Output: US6446444/code/<NAME> plus a page map (code/PAGE_MAP.md).
Usage: python3 -I assemble_code.py <corrected_dir>
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'US6446444' / 'code'
HEADING = re.compile(r'^\s*([A-Z_]+(?:\.[A-Z]+)?)(?: \(LINKER\))? MODULE\s*$')
# Printed heading -> file name, where the heading misspells the module
RENAME = {'KERNAL.H': 'KERNEL.H'}


def main():
    pages = sorted(Path(sys.argv[1]).glob('p-*.txt'))
    modules, order, current = {}, [], None
    page_map = {}
    for page_path in pages:
        page = int(page_path.stem[2:])
        for line in page_path.read_text().splitlines():
            match = HEADING.match(line)
            if match:
                current = RENAME.get(match.group(1), match.group(1))
                assert current not in modules, f'module {current} seen twice'
                modules[current] = []
                order.append((current, line.strip()))
                page_map[current] = []
                continue
            if current is None:
                continue
            if not page_map[current] or page_map[current][-1][0] != page:
                page_map[current].append((page, len(modules[current]) + 1))
            modules[current].append(line.rstrip())
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    for name, heading in order:
        lines = modules[name]
        while lines and not lines[0].strip():
            lines.pop(0)
            page_map[name][0] = (page_map[name][0][0], page_map[name][0][1])
        while lines and not lines[-1].strip():
            lines.pop()
        (OUT / name).write_text('\n'.join(lines) + '\n')
        spans = ', '.join(f'p{page}' for page, _ in page_map[name])
        first, last = page_map[name][0][0], page_map[name][-1][0]
        rows.append(f'| `{name}` | `{heading}` | {first}-{last} | {len(lines)} | {spans} |')
        print(f'{name:14} pages {first}-{last}  {len(lines)} lines')
    detail = []
    for name, _ in order:
        starts = '; '.join(f'p{page} → line {line}' for page, line in page_map[name])
        detail.append(f'- `{name}`: {starts}')
    (OUT / 'PAGE_MAP.md').write_text(
        '# Appendix page map\n\nGenerated by `tools/assemble_code.py`. PDF page numbers refer to '
        '`US6446444/US6446444.pdf`.\n\n| File | Printed heading | PDF pages | Lines | Pages |\n'
        '|---|---|---|---|---|\n' + '\n'.join(rows) + '\n\n## Where each page starts in the file\n\n'
        'Line numbers are approximate to ±2 (leading blank lines are trimmed).\n\n'
        + '\n'.join(detail) + '\n')


if __name__ == '__main__':
    main()
